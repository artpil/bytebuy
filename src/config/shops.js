export const getShopBySlug = (slug) => SHOPS.find((s) => s.slug === slug)

export const buildAffiliateLink = (shopSlug, productUrl) => {
  const shop = getShopBySlug(shopSlug)
  if (!shop || !productUrl) return '#'

  const link = new URL(shop.baseLink)
  link.searchParams.set('ulp', productUrl)
  if (shop.erid) link.searchParams.set('erid', shop.erid)

  return link.toString()
}
